//! Human-facing HTML (DESIGN.md §11).
//!
//! Four rules hold this together, and each one is load-bearing:
//!
//! - **Only a human reads it.** No agent opens one of these files back;
//!   everything an agent needs stays behind `--json`. The moment a page becomes
//!   agent input it starts costing tokens against the §13 budget, and the same
//!   content in HTML costs several times what the markdown it came from does.
//! - **One file, no network.** These open from `file://`, often over SSH or
//!   WSL. Every style and script is inline and nothing is fetched.
//! - **No control that changes state.** The page informs; the terminal decides.
//!   A button that approved a spec would make the terminal check in `gate.rs`
//!   meaningless, and that check is the only thing standing between an
//!   enthusiastic agent and its own approval.
//! - **Regenerated, never edited.** Hence the banner, and hence
//!   `.bevel/cache/`, which is already ignored by git.

use anyhow::{Context, Result};
use std::path::{Path, PathBuf};

use crate::project::Project;

/// One page. Callers build `body` from the helpers below and hand it over.
pub struct Page {
    pub title: String,
    pub subtitle: String,
    /// The command that regenerates this file, shown in the footer.
    pub regenerate: String,
    pub body: String,
}

impl Page {
    pub fn new(title: impl Into<String>, regenerate: impl Into<String>) -> Self {
        Self {
            title: title.into(),
            subtitle: String::new(),
            regenerate: regenerate.into(),
            body: String::new(),
        }
    }

    pub fn subtitle(mut self, s: impl Into<String>) -> Self {
        self.subtitle = s.into();
        self
    }

    pub fn body(mut self, s: impl Into<String>) -> Self {
        self.body = s.into();
        self
    }

    pub fn render(&self) -> String {
        let sub = if self.subtitle.is_empty() {
            String::new()
        } else {
            format!("<p class=sub>{}</p>", escape(&self.subtitle))
        };
        format!(
            "<!doctype html>\n\
             <!-- Generated by bevel. Regenerate with `{}`; edits here are lost.\n\
             \x20    Read-only by design: nothing on this page can change project state. -->\n\
             <html lang=en><head><meta charset=utf-8>\n\
             <meta name=viewport content=\"width=device-width,initial-scale=1\">\n\
             <title>{}</title>\n<style>{CSS}</style>\n</head><body>\n\
             <header><h1>{}</h1>{sub}</header>\n\
             <main>{}</main>\n\
             <footer>Generated by bevel. <code>{}</code> regenerates it. \
             Nothing here changes state — the terminal decides.</footer>\n\
             </body></html>\n",
            escape(&self.regenerate),
            escape(&self.title),
            escape(&self.title),
            self.body,
            escape(&self.regenerate),
        )
    }
}

/// Write into `.bevel/cache/`, report the path, and optionally open it.
pub fn write(project: &Project, name: &str, page: &Page, open: bool) -> Result<PathBuf> {
    let dir = project.cache_dir();
    std::fs::create_dir_all(&dir)?;
    let path = dir.join(name);
    std::fs::write(&path, page.render())
        .with_context(|| format!("cannot write {}", path.display()))?;
    if open {
        launch(&path);
    }
    Ok(path)
}

/// Best effort. A viewer that will not start is not a reason to fail a report
/// that has already been written — the path is printed either way.
///
/// The empty argument on Windows is not a typo: `start` reads its first quoted
/// argument as a window title, so `start "C:\...\board.html"` opens an empty
/// console named after the file instead of the file.
fn launch(path: &Path) {
    let line = if cfg!(target_os = "macos") {
        format!("open {}", quote(&path.to_string_lossy()))
    } else if cfg!(windows) {
        format!("start \"\" {}", quote(&path.to_string_lossy()))
    } else {
        format!("xdg-open {}", quote(&path.to_string_lossy()))
    };
    let _ = crate::shell::command(&line)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status();
}

fn quote(s: &str) -> String {
    if cfg!(windows) {
        format!("\"{s}\"")
    } else {
        format!("'{}'", s.replace('\'', r"'\''"))
    }
}

pub fn escape(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            _ => out.push(c),
        }
    }
    out
}

/// Markdown as it is written in this repo: tables, task lists, strikethrough.
///
/// Raw HTML in the source is escaped rather than passed through. These files
/// are the project's own, so the risk is not injection but silent breakage —
/// the template comments in `spec.md` would otherwise vanish into the markup
/// and take the guidance they carry with them.
pub fn markdown(md: &str) -> String {
    use pulldown_cmark::{html, Options, Parser};
    let mut options = Options::empty();
    options.insert(Options::ENABLE_TABLES);
    options.insert(Options::ENABLE_STRIKETHROUGH);
    options.insert(Options::ENABLE_TASKLISTS);
    options.insert(Options::ENABLE_FOOTNOTES);
    let mut out = String::new();
    html::push_html(&mut out, Parser::new_ext(md, options));
    out
}

/// A card: the unit every report is built from.
pub fn card(title: &str, body: &str) -> String {
    format!(
        "<section class=card><h2>{}</h2>{body}</section>\n",
        escape(title)
    )
}

/// A short coloured label. `kind` is a CSS class, not free text.
pub fn pill(kind: &str, text: &str) -> String {
    format!("<span class=\"pill {kind}\">{}</span>", escape(text))
}

/// A horizontal bar against a limit.
///
/// The limit sits at 71.4% of the track rather than at the end, so that going
/// over is drawn rather than clipped: a file at twice its budget and a file
/// three lines past it are not the same problem, and a full bar for both would
/// say they were.
pub fn meter(value: usize, limit: usize, label: &str) -> String {
    const LIMIT_AT: f64 = 71.4;
    let pct = (value as f64 / limit.max(1) as f64 * 100.0).min(140.0);
    format!(
        "<div class=meter><div class=\"fill{}\" style=\"width:{:.1}%\"></div>\
         <span class=marker></span></div><span class=meterlabel>{}</span>",
        if value > limit { " over" } else { "" },
        (pct * LIMIT_AT / 100.0).min(100.0),
        escape(label)
    )
}

/// A single bar split by composition, with its legend. Proportions only —
/// segments carry their own number in the legend rather than on the bar, which
/// stops the smallest slice from being an unreadable sliver of text.
pub fn stacked(parts: &[(&str, usize)]) -> String {
    let total: usize = parts.iter().map(|(_, n)| n).sum();
    if total == 0 {
        return String::new();
    }
    let bar: String = parts
        .iter()
        .enumerate()
        .filter(|(_, (_, n))| *n > 0)
        .map(|(i, (_, n))| {
            format!(
                "<i class=s{} style=\"width:{:.2}%\"></i>",
                i + 1,
                *n as f64 / total as f64 * 100.0
            )
        })
        .collect();
    let legend: String = parts
        .iter()
        .enumerate()
        .map(|(i, (label, n))| {
            format!(
                "<span><i class=s{}></i>{} — {n}</span>",
                i + 1,
                escape(label)
            )
        })
        .collect();
    format!("<div class=stack>{bar}</div><div class=legend>{legend}</div>")
}

/// An inline SVG line chart. Empty input yields an honest note rather than an
/// empty axis, because "no history" and "flat history" are different facts.
pub fn line_chart(points: &[(String, usize)], caption: &str) -> String {
    if points.len() < 2 {
        return format!(
            "<p class=empty>Not enough history to plot a trend yet ({} point{}).</p>",
            points.len(),
            if points.len() == 1 { "" } else { "s" }
        );
    }
    let (w, h) = (720.0_f64, 220.0_f64);
    let (pad_l, pad_b, pad_t) = (52.0_f64, 28.0_f64, 12.0_f64);
    let max = points.iter().map(|p| p.1).max().unwrap_or(1).max(1) as f64;
    let n = points.len() as f64;

    let x = |i: usize| pad_l + (w - pad_l - 8.0) * (i as f64) / (n - 1.0);
    let y = |v: usize| pad_t + (h - pad_t - pad_b) * (1.0 - v as f64 / max);

    let path: String = points
        .iter()
        .enumerate()
        .map(|(i, p)| {
            format!(
                "{}{:.1} {:.1}",
                if i == 0 { "M" } else { " L" },
                x(i),
                y(p.1)
            )
        })
        .collect();
    let area = format!(
        "{path} L{:.1} {:.1} L{:.1} {:.1} Z",
        x(points.len() - 1),
        h - pad_b,
        x(0),
        h - pad_b
    );

    let dots: String = points
        .iter()
        .enumerate()
        .map(|(i, p)| {
            format!(
                "<circle cx={:.1} cy={:.1} r=3><title>{} — {} lines</title></circle>",
                x(i),
                y(p.1),
                escape(&p.0),
                p.1
            )
        })
        .collect();

    // First and last only: a label per commit is unreadable past a dozen points.
    let first = &points[0].0;
    let last = &points[points.len() - 1].0;

    format!(
        "<figure class=chart><svg viewBox=\"0 0 {w} {h}\" role=img \
         aria-label=\"{}\"><path class=area d=\"{area}\"/>\
         <path class=line d=\"{path}\"/>{dots}\
         <line class=axis x1={pad_l} y1={:.1} x2={w} y2={:.1}/>\
         <text class=tick x=8 y={:.1}>{}</text>\
         <text class=tick x=8 y={:.1}>0</text>\
         <text class=tick x={pad_l} y={h} text-anchor=start>{}</text>\
         <text class=tick x={w} y={h} text-anchor=end>{}</text>\
         </svg><figcaption>{}</figcaption></figure>",
        escape(caption),
        h - pad_b,
        h - pad_b,
        pad_t + 4.0,
        max as usize,
        h - pad_b,
        escape(first),
        escape(last),
        escape(caption),
    )
}

