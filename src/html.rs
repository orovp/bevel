#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_page_is_self_contained_and_says_it_is_generated() {
        let html = Page::new("Report", "bevel review 7")
            .subtitle("0007 example")
            .body("<p>hi</p>")
            .render();
        assert!(html.starts_with("<!doctype html>"));
        assert!(html.contains("Generated by bevel"));
        assert!(html.contains("bevel review 7"));
        // No request may leave the page: it opens from file:// with no network.
        for probe in ["http://", "https://", "//cdn", "src=", "@import"] {
            assert!(!html.contains(probe), "external reference `{probe}`");
        }
    }

    /// The gate is a terminal check. A page that could act on the project would
    /// route around it, so the markup must not contain the means.
    #[test]
    fn a_page_carries_no_control_that_could_change_state() {
        let html = Page::new("Report", "bevel review 7")
            .body(card("Criteria", "<p>x</p>"))
            .render();
        for probe in ["<form", "<button", "<input", "onclick", "fetch("] {
            assert!(!html.contains(probe), "interactive control `{probe}`");
        }
    }

    #[test]
    fn markup_in_a_title_cannot_escape_into_the_page() {
        let html = Page::new("<script>alert(1)</script>", "bevel board").render();
        assert!(!html.contains("<script>alert"));
        assert!(html.contains("&lt;script&gt;"));
    }

    #[test]
    fn markdown_renders_the_forms_the_repo_actually_uses() {
        let out = markdown("# H\n\n| a | b |\n|---|---|\n| 1 | 2 |\n\n`code`\n");
        assert!(out.contains("<h1>H</h1>"));
        assert!(out.contains("<table>"));
        assert!(out.contains("<code>code</code>"));
    }

    #[test]
    fn a_trend_needs_two_points_before_it_claims_one() {
        assert!(line_chart(&[], "x").contains("Not enough history"));
        assert!(line_chart(&[("a".into(), 1)], "x").contains("Not enough history"));
        let two = line_chart(&[("a".into(), 1), ("b".into(), 9)], "harness lines");
        assert!(two.contains("<svg"));
        assert!(two.contains("harness lines"));
    }

    #[test]
    fn a_meter_past_its_limit_is_marked_rather_than_clipped() {
        assert!(meter(120, 50, "120/50").contains("over"));
        assert!(!meter(30, 50, "30/50").contains("over"));
    }
}
